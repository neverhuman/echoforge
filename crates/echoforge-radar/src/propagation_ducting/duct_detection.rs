#[cfg(test)]
mod tests {
    use super::*;

    /// Standard atmosphere gradient (-40 N/km) ⇒ no duct.
    #[test]
    fn standard_atmosphere_returns_none() {
        let regime = classify_duct_regime(-40.0, 4.0 / 3.0, 0.5);
        assert_eq!(regime, DuctRegime::None);
    }

    /// Super-refractive but non-trapping (-100 N/km) ⇒ no duct
    /// (handled by k-factor refraction, not by an explicit duct).
    #[test]
    fn super_refractive_returns_none() {
        let regime = classify_duct_regime(-100.0, 1.5, 0.5);
        assert_eq!(regime, DuctRegime::None);
    }

    /// Trapping gradient (-200 N/km) with amplified k-factor ⇒ surface
    /// duct. Depth should fall within the published 25-100 m envelope.
    #[test]
    fn strong_trapping_returns_surface_duct() {
        let regime = classify_duct_regime(-200.0, 2.5, 0.5);
        match regime {
            DuctRegime::Surface { height_m } => {
                assert!(
                    (25.0..=100.0).contains(&height_m),
                    "surface duct height {height_m} m outside 25-100 m envelope"
                );
            }
            other => panic!("expected Surface duct, got {other:?}"),
        }
    }

    /// Trapping gradient at -157 N/km is right at the threshold; just
    /// below it (e.g. -158) should classify as Surface; just above
    /// (-156) should be None. Pin both edges.
    #[test]
    fn trapping_threshold_edge_behaviour() {
        let just_above = classify_duct_regime(-156.0, 2.5, 0.5);
        assert_eq!(just_above, DuctRegime::None);
        let just_below = classify_duct_regime(-158.0, 2.5, 0.5);
        assert!(matches!(just_below, DuctRegime::Surface { .. }));
    }

    /// Trapping gradient WITHOUT amplified k-factor (k = 4/3) ⇒ should
    /// still return None — robust surface ducts require k > 2.
    #[test]
    fn trapping_gradient_low_k_returns_none() {
        let regime = classify_duct_regime(-200.0, 4.0 / 3.0, 0.5);
        assert_eq!(regime, DuctRegime::None);
    }

    /// Marine humidity 0.78 (typical warm sea) ⇒ evaporation duct
    /// height in the 7-12 m range per Paulus/Hitney tables.
    #[test]
    fn marine_humidity_returns_evaporation_duct() {
        let regime = classify_duct_regime(-40.0, 4.0 / 3.0, 0.78);
        match regime {
            DuctRegime::Evaporation { height_m } => {
                assert!(
                    (7.0..=12.0).contains(&height_m),
                    "evaporation duct height {height_m} m outside 7-12 m for RH=0.78"
                );
            }
            other => panic!("expected Evaporation duct, got {other:?}"),
        }
    }

    /// Very humid surface (RH = 0.97) ⇒ above the evaporation-duct
    /// upper bound, no duct.
    #[test]
    fn very_humid_returns_none() {
        let regime = classify_duct_regime(-40.0, 4.0 / 3.0, 0.97);
        assert_eq!(regime, DuctRegime::None);
    }

    /// Dry desert surface (RH = 0.2) ⇒ below the evaporation-duct
    /// lower bound, no duct.
    #[test]
    fn dry_surface_returns_none() {
        let regime = classify_duct_regime(-40.0, 4.0 / 3.0, 0.2);
        assert_eq!(regime, DuctRegime::None);
    }

    /// Evaporation-duct height is monotonically decreasing in RH across
    /// the valid envelope (drier ⇒ deeper duct).
    #[test]
    fn evaporation_duct_height_monotonic_in_rh() {
        let h_low = evaporation_duct_height_m(0.72);
        let h_high = evaporation_duct_height_m(0.92);
        assert!(
            h_low > h_high,
            "expected drier RH to give deeper duct: h(0.72)={h_low} h(0.92)={h_high}"
        );
    }

    /// Surface-duct depth is monotonically increasing in gradient
    /// steepness (more negative gradient ⇒ thicker layer).
    #[test]
    fn surface_duct_depth_monotonic_in_gradient() {
        let d_weak = surface_duct_depth_m(-160.0);
        let d_strong = surface_duct_depth_m(-300.0);
        assert!(
            d_strong > d_weak,
            "expected steeper gradient to give deeper duct: weak={d_weak} strong={d_strong}"
        );
    }

    /// Construction of an Elevated duct variant works as documented
    /// (callers with layered profiles build it directly; the classifier
    /// never returns it).
    #[test]
    fn elevated_duct_variant_constructible() {
        let elev = DuctRegime::Elevated {
            base_m: 800.0,
            top_m: 1000.0,
        };
        match elev {
            DuctRegime::Elevated { base_m, top_m } => {
                assert!(top_m > base_m);
            }
            _ => panic!("Elevated variant should be constructible"),
        }
    }
}
